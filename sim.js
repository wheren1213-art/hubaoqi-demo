  // 玩家会以为 AI 退化了；有了它才有"撞上巡逻队"和"绕过巡逻队"。
  function patrolStep(e){
    const route=e.patrol;
    e.stance='MARCH';               // 巡逻是常行：在找人，但没绷紧（所以玩家从侧面摸过来还有机会）
    if(!route||!route.length){e.path=[];e.state='驻守';return;}
    // **归队优先**（54）：人在巡防区外就先回区，再谈巡逻。
    //   为什么要有：扩图后从西岸撤回东岸要走 20 多格，中途阶段已经从 PRESS 落回 PATROL，
    //   于是它拿着"区内航点"在区外原地找路——findPath 的 avoid 是巡防区，出圈之后恒为 null，
    //   四次跳点轮完就站着不动（实测敌枪兵丙停在西岸 x=75 整整 30 秒，玩家以为它卡了）。
    //   这段不改 clampToZone：那里"在区外就不夹"是 52 为了过河特意留的口子，动了会把 PRESS 也夹回来。
    const Z=PATROL.ZONE;
    if(Math.round(e.x)<Z.x1-1||Math.round(e.x)>Z.x2+1||Math.round(e.y)<Z.y1-1||Math.round(e.y)>Z.y2+1){
      const tx=Math.max(Z.x1,Math.min(Z.x2,Math.round(e.x)));
      const ty=Math.max(Z.y1,Math.min(Z.y2,Math.round(e.y)));
      if(!e.path.length){
        const p=findPath(e,Math.round(e.x),Math.round(e.y),tx,ty);
        e.path=p||[];
      }
      e.state=e.path.length?'巡逻':'待命';
      return;
    }
    const wp=route[e.patrolIdx%route.length];
    if(distance(e,wp)<=PATROL.ARRIVE){
      e.path=[];
      if(e.patrolWait<=0){e.patrolWait=PATROL.WAIT;e.patrolIdx=(e.patrolIdx+1)%route.length;}
      e.state='巡逻';
      return;
    }
    if(!e.path.length){
      // 先按巡防区走；圈内确实到不了（比如被挤出圈外）再放开，否则会一直跳点、原地打转
      const p=findPath(e,Math.round(e.x),Math.round(e.y),wp.x,wp.y,PATROL.ZONE)
           ||findPath(e,Math.round(e.x),Math.round(e.y),wp.x,wp.y);
      e.path=p||[];
      if(!e.path.length){e.patrolIdx=(e.patrolIdx+1)%route.length;}   // 走不过去就跳过这个点
    }
    e.state='巡逻';
  }
