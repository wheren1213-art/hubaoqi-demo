  //   WeakMap 持有，d 层不再有这些字段。
  // ★ 别把它们搬回来：兵是**表现**不是实体，战斗/寻路/占位只认 `units[]` 一条记录（一支＝一格）。
  //
  // 这里只留一条模拟侧的查询：`foesWithin(u, r)`＝"u 身边 r 格内有几个活着的敌人"。
  //   它本来就是纯读，e1 用它判"三面被围 → 圆阵"；留在 d 层是因为它读的是 units/enemies
  //   两份模拟数据，而且以后士气、包夹结算也该用同一个口径，不该在两边各写一份。
  function foesWithin(u, r) {
    const pool = u.team === 'blue' ? enemies : units;
    let n = 0;
    for (const o of pool) if (o.hp > 0 && Math.hypot(o.x - u.x, o.y - u.y) <= r) n++;
    return n;
  }

  // ── 阵型（2026-10-28 ㊵）：**只记状态，不进任何数值计算** ────────────
  // 设定是"成阵迎战有加成，撤退/强攻等会破阵"。加成怎么算还没定，
  //   所以 BONUS 故意留 1.0 当占位，伤害/士气/防御一处都不读 formation。
  // 以后接机制只改两个地方：BONUS 的数值 + 它的消费点（attack 里），
  //   不要在别处散着判 u.formation，否则又是两套规则并存。
  const FORMATION = {
    BONUS: 1.0,               // ← 占位：成阵伤害/防御系数，当前恒为 1（等于没有）
    REGAIN_SEC: 6,            // 站定且未接敌满 6 秒，重新结阵
    BREAK_ORDERS: ['RETREAT', 'ATTACK']   // 撤退、强攻在途即破阵
  };
  function breakFormation(u, why) {
    if (!u || u.hp <= 0) return false;
    u.formationSteady = 0;
    if (u.formation === 'BROKEN') { u.formationWhy = why; return false; }
    u.formation = 'BROKEN'; u.formationWhy = why;
    return true;
  }
  function updateFormation(u, dt) {
    if (u.hp <= 0) return;
    if (u.isRouted) { breakFormation(u, '溃退'); return; }
    if (FORMATION.BREAK_ORDERS.includes(u.order)) {
      // 98：冲锋期间破阵原因要写「全力冲锋」，不能每步被「强攻」覆回去（Q40 要 formationWhy）。
      breakFormation(u, u.rush ? '全力冲锋' : (u.order === 'RETREAT' ? '撤退' : '强攻'));
      return;
    }
    if (u.formation === 'BROKEN') {
      if (u.path.length || u.targetId) { u.formationSteady = 0; return; }
      u.formationSteady += dt;
      if (u.formationSteady >= FORMATION.REGAIN_SEC) {
        u.formation = 'FORMED'; u.formationWhy = null; u.formationSteady = 0;
      }
    }
  }

  // ── 将领（2026-10-28 ㊵）：部队不全灭，将领不死 ──────────────────
  // 主将和以后的各级将领共用这一条判定：将不单独持有血量，它的命挂在部队上。
  // 特殊死法（斩首、刺杀、突围失败、乱箭）将来从这里开口子：让 deathCheck 返回 true。
  // **本轮 deathCheck 恒 false**，也就是只有"部队全灭"能带走将领。
  const LEADER = {
    deathCheck(u, ctx) { return false; }   // ctx = {cause, attacker}
  };
  // ── 活捉（97）：把"部队被打垮那一刻"的结算，从"将必死"改成"将可俘" ────────
  // **它不是"更客气的攻击"**：兵照打、照挨打、照掉血、照溃退，唯一改动的是
  //   `attack()` 里 `target.hp===0` 那一帧的结局判定——本来必死的将，掷一次，抓到就是俘。
  //   所以它是 STATE（兵不动、只改结算），而不是 ATTACK 的一个参数。
  //
  // CHANCE 故意留在 **1＝有将必俘**，不是在替上司定概率：
  //   "打垮之后将死不死"是数值设计，值没定之前先按"说到做到"跑（玩家说活捉就该抓到）。
  //   定下来只改这一个数，结算路径不用动。骰子本身是真的（见 captureRoll），
  //   capture_test 把 CHANCE 临时调到 0/0.5 验证两条分支都真会走。
  //
  // 没有"火力打八折"这类代价：AGENTS.md 与 ACTIONS.md §4.3 都写着那属于数值设计待定，
  //   值没定就先不扣——凭空扣 20% 是编数字，不是实现。要加就加在 attack() 的 damage 那一行，
  //   别在别处散着判 captureMode（那就是两套规则并存）。
  const CAPTURE = { CHANCE: 1 };
  function leaderFalls(u, ctx) {
    const L = u.leader;
    if (!L || !L.alive) return false;
    if (u.hp <= 0) return true;                        // 部队全灭 → 将领必死
    return LEADER.deathCheck(u, ctx) === true;         // 部队尚存 → 只有特殊规则能夺命
  }
  // 将的结局只有两种，`alive:false` 对两者都成立（这样"主将还在不在"仍然只有一处判据），
  //   区别只写在 `captured` 上：**被俘是活着离开战场，战死是没了**。回执、结局文案读它。
  function retireLeader(u,how){
    if(!u.leader)return;
    u.leader.alive=false;
    if(how==='captured')u.leader.captured=true;
  }
  // 给非主将部队配将（需求 4 的接口）。将领不可控、只加参数——
