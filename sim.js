  // ── 条件触发（78）：c 层说"等什么"，这里算"成不成" ─────────────────────
  // 分工不能反：**只有 d 层有位置、视野和敌人**，所以真假只在这里算；
  //   c 层只负责把 b 层那句话装进 step.when，并决定"何时问一次"。
  // 四种条件（arrived 不在这里判——它判的是上一段的部队，是 c 层的活）：
  //   elapsed{sec}     —— 从上一段下达算起的模拟秒
  //   sight{who,dist}  —— 看着的那几支里有人真看得见符合条件的敌（canSee：视距＋山脊＋林冠）
  //   foeDown{foeId}   —— 那支敌军已经没了（阵亡或不存在）
  // 看不到就是没看到：不做"大概在那个方向"的推测。推测等于替玩家开图。
  function foeMatchesKind(e,w){
    if(!w||!w.who||w.who==='foe')return true;
    if(w.who==='commander')return !!(e.leader&&e.leader.alive!==false&&e.leader.kind==='commander');
    return true;
  }
  function watchersOf(ids){
    const out=[];
    for(const id of (ids||[])){
      const list=id==='ALL'?units:[units.find(u=>u.id===id)];   // 'ALL' 是哨兵值，不是 id
      for(const u of list)if(u&&u.hp>0&&!u.isRouted&&out.indexOf(u)<0)out.push(u);
    }
    return out;
  }
  function condMet(when,ids,since){
    const w=when||{kind:'arrived'};
    if(w.kind==='elapsed')return simTime-(since||0)>=(w.sec||0);
    if(w.kind==='foeDown'){const e=enemies.find(x=>x.id===w.foeId);return !e||e.hp<=0;}
    if(w.kind==='sight'){
      const watch=watchersOf(ids);
      if(!watch.length)return false;
      const cand=enemies.filter(e=>e.hp>0&&!e.isRouted&&foeMatchesKind(e,w));
      if(!cand.length)return false;
      return watch.some(u=>cand.some(e=>
        (w.dist==null||distance(u,e)<=w.dist)&&canSee(u,e)));
    }
    return true;
  }
  // ── 压制（78）：伏着不动，不主动接敌 ─────────────────────────────────
