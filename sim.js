  //   不许两支挤在一起 —— 那是分配策略，不是占位硬规则。行军途中的瞬时挤压不硬拦
  //   （拦了会卡死：前面的部队不走，后面的一直等），画面那一层保证它们永远画得开。
  const OVERLAP = { CAP:3, MIN_SEP:.6 };

  // ── 编制 / 阵型模板（**2026-10-31 67 起迁到 troop.js，e1 层**）──────────────
  // 一支部队画成九个兵、六套阵型模板、进位过渡、编队包围盒，全部在 `troop.js`（全局名 TROOP）。
  // 它们从来就不是模拟：不读也不写任何战斗字段，只回答"这一簇画在哪"。
