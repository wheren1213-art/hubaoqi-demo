  //   因为当时唯一的负高度是河（站不进去）。洼地能站之后那层 clamp 会把 −1 悄悄抹成 0，
  //   "站低处看得近"就变成了一条永远不成立的规则（terrain_vision_test [2] 能抓到）。
  function eyeHeight(u){return heightAt(Math.round(u.x),Math.round(u.y));}
  // 视线能看多远：返回"沿这条线最远能看清的距离"，没挡住返回 Infinity。
  // 两种截断取更近的那个：
  //   山脊 = 硬截断（最近的挡路格，视线到此为止）；
  //   林冠 = 一层树后还透 PIERCE 格，**两层树就挡住**（复层林没有缝可透）。
  // 先扫完全程再取 min，而不是边扫边 return：边扫边返回会在"树近山远"时漏掉更近的树。
  // 只用格地形判定，不读单位：所以"站高处看得远"和"山那边是盲区"是同一条公式的两个结果。
  function losCap(ax,ay,bx,by){
    const dx=bx-ax, dy=by-ay;
    const steps=Math.max(Math.abs(dx),Math.abs(dy));
    if(steps<2)return Infinity;                       // 贴脸/相邻，没有中间的格可挡
    const hA=heightAt(ax,ay), hB=heightAt(bx,by);
    // 98（Q3b/Q12）：**方向性高度** —— 只用观察者高度，不用两端较高者。
    //   旧写法 `max(hA,hB)+RIDGE` 会让"站山脚看山顶"也无端被挡，站高处越过山脊就不成立。
    //   目标站高地时低处照样过不去（hA 低 → top 低 → 中途 hill 更容易超）。
    const top=hA+SIGHT.RIDGE;
    const dist=Math.hypot(dx,dy);
    let trees=0, firstTree=-1, ridgeAt=Infinity;
    for(let i=1;i<steps;i++){
      const t=i/steps;
      const x=Math.round(ax+dx*t), y=Math.round(ay+dy*t);
      const at=(i/steps)*dist;
      if(heightAt(x,y)>top){ridgeAt=at;break;}        // 最近的一道山脊：再往后都看不见
      // 98（Q22）：山脊判据读 base（上面的 heightAt），树冠判据读 cover，两条截断取更近的。
      if(inside(x,y)&&isForest(x,y)){trees++;if(firstTree<0)firstTree=at;}
    }
    const canopy=trees===0?Infinity:(trees>=2?firstTree:firstTree+SIGHT.PIERCE);
    return Math.min(canopy,ridgeAt);
  }

