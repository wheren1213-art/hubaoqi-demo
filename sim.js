  // 取 t-lag 时刻的快照，并在相邻两条之间插值——否则位置会每 0.25 秒向后跳一格
  function sampleOf(u, at) {
    const arr = hist.get(u.id);
    if (!arr || !arr.length) return null;
    let prev = arr[0], next = null;
    for (const s of arr) { if (s.t <= at) prev = s; else { next = s; break; } }
    if (!next) return prev;
    const span = next.t - prev.t;
    const k = span > 0 ? Math.min(1, Math.max(0, (at - prev.t) / span)) : 0;
    return Object.assign({}, prev, { x: prev.x + (next.x - prev.x) * k, y: prev.y + (next.y - prev.y) * k });
  }
