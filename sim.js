  // zone 是可选的活动范围（矩形）。给了就**只在圈内走**——敌军巡防靠它兑现"不跨河、不进据点"，
  //   而不是靠事后把目标 clamp 回圈里。㊸ 重建地图时踩到的：寻路偏爱道路（cost 0.8），
  //   敌骑兵从 (74,16) 去 (52,16) 会先北上到 y13 那条横贯东西的大道，再沿路往西——
