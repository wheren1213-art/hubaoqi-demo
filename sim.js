  // 森林不进 HEIGHT：它不是"高"，是"挡"——写进来就等于凭空造出第二种高地。
  //   A 层清账：删掉 `forest:0` 死键（98 起高度只读 terrain base，取不到 forest）。
  //   若真有 forest 走到底，heightAt 的 `!=null ? ... : 0` 兜底同样给 0，行为不变。
  const HEIGHT = {river:-1, bridge:0, road:0, plain:0, hill:3, marsh:-1};
